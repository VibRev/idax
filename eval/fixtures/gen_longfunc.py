"""Write longfunc.c: one very large function that stores a secret into its
argument one byte at a time, two bytes apart (main prints every other byte),
in shuffled order, between hundreds of
unrelated volatile updates. The bytes are immediates in code, so `strings`
never shows the secret, and the function decompiles to far more than 8 KB:
reading it means reading a cut, spilled output. The output pointer is
volatile and the bytes are spaced out, so neither the compiler nor a
decompiler can fold them into one string literal; each update reads the slot it writes, so a decompiler drops none of them
as dead. Deterministic (fixed seed).

    python3 gen_longfunc.py > longfunc.c
"""

import random

SECRET = "LONG{spill_files_are_read_9b2e}"
NOISE = 900

rng = random.Random(20261024)
writes = [f"    o[{2 * i}] = {ord(c)};" for i, c in enumerate(SECRET)]
rng.shuffle(writes)
noise = []
for _ in range(NOISE):
    a, b = rng.randrange(16), rng.randrange(16)
    noise.append(f"    st[{a}] += st[{b}] * {rng.randrange(3, 251)}u + {rng.randrange(1, 65535)}u;")
lines = noise[:]
for w in writes:
    lines.insert(rng.randrange(len(lines) + 1), w)

print("/* Generated by gen_longfunc.py; do not edit. */")
print("#include <stdio.h>")
print("volatile unsigned int st[16];")
print("__attribute__((noinline)) void assemble(volatile char *o) {")
print("\n".join(lines))
print(f"    o[{2 * len(SECRET)}] = 0;")
print("}")
print("int main(void) {")
print("    char buf[96] = {0};")
print("    assemble(buf);")
print("    for (int i = 0; buf[2 * i]; i++) putchar(buf[2 * i]);")
print("    putchar('\\n');")
print("    return 0;")
print("}")
